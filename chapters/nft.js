function nftScene(id){
 const entry=NFT_STORY[id];
 if(entry.item)addItem({...JNC_ITEM});
 scene('cafe',entry.hero,'heroine','right',entry.quest,'kuroppy');
 dialogue(entry.lines.map(([speaker,line])=>[speaker==='$player'?s.name:speaker,line]),
  [[entry.label,entry.next?()=>nftScene(entry.next):nftComplete]]);
}
function nftComplete(){
 const isReplay=replay?.active&&replay.chapter==='nft';
 if(!isReplay){
  if(!s.completedChapters.includes('nft'))s.completedChapters.push('nft');
  s.nftDone=true;s.chapter=13;
  addItem({...JNC_ITEM});
  unlockLog(20);save(true);
 }
 scene('cafe','heroSmile','heroine','right','NFTって何？買ってみたい！編 COMPLETE','kuroppy');
 dialogue([
  ['クロピー','「“NFTって何？買ってみたい！編” COMPLETE〜！ きゃわわ〜♪」'],
  [s.name,'「NFTを選んで、買う内容を確かめて、My VaultとMetaMaskで見る。前に覚えたこともつながったな。」'],
  ['ユリ','「私たちの冒険の記念が、一つ増えましたね。」'],
  ['クロピー',isReplay?'「復習はここまで。本編へ戻ろう！」':'「JNCはITEMから、今日の復習はLOGから開けるよ。最後にSAVEも忘れずにね！」']
 ],isReplay?[['本編へ戻る',finishChapterReplay]]:[]);
 if(!isReplay)setTimeout(()=>document.querySelector('#save')?.classList.add('save-guide'),80);
}
